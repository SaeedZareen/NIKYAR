/** «IR06 0170 …» ← «بانک ملی ایران» */
export function bankFromIban(iban: string): string | undefined {
  return /^IR\d{5}/.test(iban) ? IBAN_BANKS[iban.slice(4, 7)] : undefined
}

export function bankFromCard(card: string): string | undefined {
  return card.length >= 6 ? CARD_BANKS[card.slice(0, 6)] : undefined
}
